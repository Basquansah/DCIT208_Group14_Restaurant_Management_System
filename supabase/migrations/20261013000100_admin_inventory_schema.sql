CREATE TABLE IF NOT EXISTS public.ingredients (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name VARCHAR(255) NOT NULL UNIQUE,
  unit VARCHAR(50) NOT NULL CHECK (unit IN ('kg', 'litres')),
  current_stock DECIMAL(10, 2) NOT NULL DEFAULT 0.00 CHECK (current_stock >= 0),
  minimum_threshold DECIMAL(10, 2) NOT NULL DEFAULT 10.00 CHECK (minimum_threshold >= 0)
);

CREATE TABLE IF NOT EXISTS public.inventory_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ingredient_name TEXT NOT NULL,
  action TEXT NOT NULL CHECK (action IN ('RECEIVED', 'ISSUED_TO_KITCHEN')),
  quantity NUMERIC(10, 2) NOT NULL CHECK (quantity > 0),
  unit TEXT NOT NULL,
  staff_name TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION public.record_inventory_movement(
  p_ingredient_id UUID,
  p_action TEXT,
  p_quantity NUMERIC,
  p_staff_name TEXT
)
RETURNS TABLE (
  id UUID,
  name VARCHAR(255),
  unit VARCHAR(50),
  current_stock NUMERIC,
  minimum_threshold NUMERIC
)
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  selected_ingredient public.ingredients%ROWTYPE;
  next_stock NUMERIC;
BEGIN
  IF p_action NOT IN ('RECEIVED', 'ISSUED_TO_KITCHEN') OR p_quantity <= 0
    OR NULLIF(BTRIM(p_staff_name), '') IS NULL THEN
    RAISE EXCEPTION 'Invalid inventory movement details.';
  END IF;

  SELECT * INTO selected_ingredient
  FROM public.ingredients
  WHERE ingredients.id = p_ingredient_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Ingredient not found.';
  END IF;

  next_stock := CASE
    WHEN p_action = 'RECEIVED' THEN selected_ingredient.current_stock + p_quantity
    ELSE selected_ingredient.current_stock - p_quantity
  END;
  IF next_stock < 0 THEN
    RAISE EXCEPTION 'Cannot issue more stock than is available.';
  END IF;

  UPDATE public.ingredients
  SET current_stock = next_stock
  WHERE ingredients.id = p_ingredient_id
  RETURNING * INTO selected_ingredient;

  INSERT INTO public.inventory_logs (ingredient_name, action, quantity, unit, staff_name)
  VALUES (
    selected_ingredient.name,
    p_action,
    p_quantity,
    selected_ingredient.unit,
    BTRIM(p_staff_name)
  );

  RETURN QUERY
  SELECT
    selected_ingredient.id,
    selected_ingredient.name,
    selected_ingredient.unit,
    selected_ingredient.current_stock,
    selected_ingredient.minimum_threshold;
END;
$$;
